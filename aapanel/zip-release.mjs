// ZIP de release do G-Fit: implementação intencionalmente restrita (ZIP32, store/deflate).
// Não use para extração genérica de ZIPs. Rejeita links, ZIP64, traversal, nomes duplicados,
// bombas de descompressão, arquivos ocultos, extras e caminhos fora do código do produto.
import {createHash} from 'node:crypto';
import {deflateRawSync,inflateRawSync} from 'node:zlib';
import {promises as fs} from 'node:fs';
import path from 'node:path';

export const ZIP_MAX_BYTES=32*1024*1024;
export const ENTRY_MAX_BYTES=8*1024*1024;
export const TOTAL_MAX_BYTES=96*1024*1024;
export const FILE_MAX=600;
export const MIN_RELEASE_FILES=[
  'package.json','api/package.json','web/package.json','api/src/server.js',
  'api/src/db.js','aapanel/launcher.mjs','aapanel/update-routes.mjs',
  'scripts/make-release.mjs',
  'aapanel/update-core.mjs','aapanel/zip-release.mjs',
  'web/index.html','web/vite.config.js','web/src/main.jsx',
];
const exact=new Set(['package.json','api/package.json','web/package.json',
  'api/package-lock.json','web/package-lock.json',
  'web/index.html','web/vite.config.js']);
const roots=['api/src/','web/src/','aapanel/','scripts/'];
export function allowedReleasePath(name) {
  if(typeof name!=='string'||name.length>240||!name||
      /[\x00-\x1f\x7f\\:]/.test(name)||
      name.startsWith('/')||name.includes('//')||
      name.split('/').some(seg=>!seg||seg==='.'||seg==='..'||seg.startsWith('.'))||
      /^(?:[A-Za-z]:|\/\/)/.test(name))return false;
  if(exact.has(name))return true;
  if(!roots.some(r=>name.startsWith(r)))return false;
  if(name.startsWith('aapanel/test/'))return false;
  if(name.split('/').some(seg=>['node_modules','dist','private','backups','updates'].includes(seg)))return false;
  // Source text and resources used by the Vite build; no executables or arbitrary archives.
  return /\.(?:mjs|js|jsx|ts|tsx|css|html|svg|json|png|jpg|jpeg|webp|ico|woff2)$/.test(name);
}
const sha=buffer=>createHash('sha256').update(buffer).digest('hex');
const table=new Uint32Array(256);
for(let i=0;i<256;i++){let c=i;for(let j=0;j<8;j++)c=(c&1)?(0xedb88320^(c>>>1)):(c>>>1);table[i]=c>>>0;}
export function crc32(data){
  let value=0xffffffff;
  for(const b of data)value=table[(value^b)&255]^(value>>>8);
  return (value^0xffffffff)>>>0;
}
export function semver(value){
  if(typeof value!=='string'||!/^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$/.test(value))return null;
  const nums=value.split('.').map(Number);
  return nums.every(Number.isSafeInteger)?nums:null;
}
export function compareVersions(a,b){
  const x=semver(a),y=semver(b);
  if(!x||!y)throw new Error('Versão inválida: use MAJOR.MINOR.PATCH.');
  for(let i=0;i<3;i++)if(x[i]!==y[i])return x[i]>y[i]?1:-1;
  return 0;
}
function validateNames(names){
  if(names.length>FILE_MAX)throw new Error('ZIP possui arquivos demais.');
  const namesSeen=new Set();
  for(const name of names){
    if(name!=='gfit-release.json'&&!allowedReleasePath(name))throw new Error('Arquivo não permitido no ZIP: '+name.slice(0,90));
    const lowered=name.toLowerCase();
    if(namesSeen.has(lowered))throw new Error('Caminho duplicado ou com colisão de letras.');
    namesSeen.add(lowered);
  }
}
export function readZip(buffer) {
  if(!Buffer.isBuffer(buffer)||buffer.length<22||buffer.length>ZIP_MAX_BYTES)throw new Error('ZIP vazio ou maior que 32 MiB.');
  // Canonical ZIP generated by this tool ends with EOCD and no appended comment.
  const end=buffer.length-22;
  if(buffer.readUInt32LE(end)!==0x06054b50)throw new Error('ZIP sem cabeçalho final válido.');
  if(buffer.readUInt16LE(end+4)!==0||buffer.readUInt16LE(end+6)!==0 ||
      buffer.readUInt16LE(end+20)!==0)throw new Error('ZIP multi-volume ou comentado não suportado.');
  const count=buffer.readUInt16LE(end+10);
  const bytes=buffer.readUInt32LE(end+12);
  const offset=buffer.readUInt32LE(end+16);
  if(count!==buffer.readUInt16LE(end+8)||count>FILE_MAX||offset+bytes!==end)throw new Error('Diretório ZIP inválido.');
  const files=new Map();
  let cursor=offset,total=0,lastLocalEnd=0;
  for(let i=0;i<count;i++){
    if(cursor+46> end||buffer.readUInt32LE(cursor)!==0x02014b50)throw new Error('Entrada central do ZIP inválida.');
    const flag=buffer.readUInt16LE(cursor+8);
    const method=buffer.readUInt16LE(cursor+10);
    const crc=buffer.readUInt32LE(cursor+16);
    const packed=buffer.readUInt32LE(cursor+20);
    const plain=buffer.readUInt32LE(cursor+24);
    const length=buffer.readUInt16LE(cursor+28);
    const extra=buffer.readUInt16LE(cursor+30);
    const comment=buffer.readUInt16LE(cursor+32);
    const external=buffer.readUInt32LE(cursor+38);
    const local=buffer.readUInt32LE(cursor+42);
    const madeBy=buffer.readUInt16LE(cursor+4);
    const mode=(external>>>16)&0xffff;
    if((flag&~0x800)!==0||![0,8].includes(method)||
       extra!==0||comment!==0||length===0||plain>ENTRY_MAX_BYTES||
       packed>ZIP_MAX_BYTES||local!==lastLocalEnd||local>=offset||
       (madeBy>>>8)===3 && ((mode&0o170000)!==0o100000)) {
      throw new Error('ZIP contém recursos inseguros ou não suportados.');
    }
    if(cursor+46+length>end)throw new Error('Nome de ZIP truncado.');
    const nameBytes=buffer.subarray(cursor+46,cursor+46+length);
    const name=nameBytes.toString('utf8');
    if(!Buffer.from(name,'utf8').equals(nameBytes))throw new Error('Nome ZIP não é UTF-8 válido.');
    cursor+=46+length;
    if(local+30+length>offset||buffer.readUInt32LE(local)!==0x04034b50||
       buffer.readUInt16LE(local+6)!==flag||
       buffer.readUInt16LE(local+8)!==method||
       buffer.readUInt32LE(local+14)!==crc||
       buffer.readUInt32LE(local+18)!==packed||
       buffer.readUInt32LE(local+22)!==plain||
       buffer.readUInt16LE(local+26)!==length||
       buffer.readUInt16LE(local+28)!==0||
       !buffer.subarray(local+30,local+30+length).equals(nameBytes)){
      throw new Error('Cabeçalho local de ZIP não confere com diretório.');
    }
    const start=local+30+length;
    if(start+packed>offset)throw new Error('Dados ZIP fora da área de arquivos.');
    const chunk=buffer.subarray(start,start+packed);
    let value;
    try{
      value=method===0?Buffer.from(chunk):inflateRawSync(chunk,{maxOutputLength:ENTRY_MAX_BYTES+1});
    }catch{throw new Error('Falha ao descompactar entrada ZIP.');}
    if(value.length!==plain||crc32(value)!==crc)throw new Error('CRC ou tamanho de ZIP inválido.');
    total+=value.length;
    if(total>TOTAL_MAX_BYTES)throw new Error('ZIP excede 96 MiB descompactados.');
    files.set(name,value);
    lastLocalEnd=start+packed;
  }
  if(cursor!==end||lastLocalEnd!==offset)throw new Error('Estrutura ZIP não canônica.');
  validateNames([...files.keys()]);
  return files;
}
export function validateRelease(buffer,currentVersion='0.1.0'){
  const files=readZip(buffer);
  const raw=files.get('gfit-release.json');
  if(!raw||raw.length>128000)throw new Error('ZIP não contém manifesto G-Fit válido.');
  let manifest;
  try{manifest=JSON.parse(raw.toString('utf8'));}catch{throw new Error('Manifesto JSON inválido.');}
  if(manifest?.format!=='gfit-release-v1'||!semver(manifest.version)||
     compareVersions(manifest.version,currentVersion)<=0||
     !Array.isArray(manifest.files))throw new Error('Release inválida ou versão não superior à atual.');
  if(manifest.files.length!==files.size-1)throw new Error('Manifesto não corresponde ao número de arquivos.');
  for(const required of MIN_RELEASE_FILES)if(!files.has(required))throw new Error('Release incompleta: '+required);
  const validated=new Set();
  for(const item of manifest.files){
    if(!item||!allowedReleasePath(item.path)||validated.has(item.path)||
       !/^[a-f0-9]{64}$/.test(item.sha256)||
       !Number.isSafeInteger(item.size)||item.size<0)throw new Error('Manifesto contém entradas inválidas.');
    const actual=files.get(item.path);
    if(!actual||actual.length!==item.size||sha(actual)!==item.sha256)throw new Error('Arquivo diverge do manifesto: '+item.path);
    validated.add(item.path);
  }
  if(manifest.files.some(({path:name})=>!files.has(name)))throw new Error('Manifesto incompleto.');
  if(sha(files.get('package.json'))!==manifest.files.find(x=>x.path==='package.json')?.sha256)throw new Error('Package inconsistente.');
  // The root app version is the baseline, while applied release version lives in private current.json.
  const rootPkg=JSON.parse(files.get('package.json').toString('utf8'));
  if(rootPkg.name!=='gfit-aapanel'||rootPkg.scripts?.start!=='node aapanel/launcher.mjs'){
    throw new Error('O ZIP não contém um projeto G-Fit válido.');
  }
  return {manifest,files,sha256:sha(buffer)};
}
export async function collectReleaseFiles(root){
  const result=new Map();
  const names=['package.json','api/package.json','web/package.json',
    'web/index.html','web/vite.config.js'];
  for(const directory of ['api/src','web/src','aapanel','scripts']){
    async function walk(dir){
      for(const item of await fs.readdir(path.join(root,dir),{withFileTypes:true})){
        const rel=dir+'/'+item.name;
        if(item.isSymbolicLink())throw new Error('Links simbólicos não são permitidos na release.');
        if(item.isDirectory()){
          if(item.name==='test')continue;
          await walk(rel);
        } else if(item.isFile() && allowedReleasePath(rel))names.push(rel);
      }
    }
    await walk(directory);
  }
  for(const pkg of ['api/package-lock.json','web/package-lock.json']){
    try{await fs.access(path.join(root,pkg));names.push(pkg);}
    catch(error){if(error.code!=='ENOENT')throw error;}
  }
  validateNames(names);
  for(const name of names){
    if(!allowedReleasePath(name))throw new Error('Caminho de release inesperado: '+name);
    const bytes=await fs.readFile(path.join(root,name));
    if(bytes.length>ENTRY_MAX_BYTES)throw new Error('Arquivo maior que 8 MiB: '+name);
    result.set(name,bytes);
  }
  for(const required of MIN_RELEASE_FILES)if(!result.has(required))throw new Error('Falta arquivo obrigatório: '+required);
  return result;
}
export function makeReleaseZip(files,version){
  if(!semver(version))throw new Error('Versão deve ser MAJOR.MINOR.PATCH.');
  validateNames([...files.keys()]);
  const entries=[...files.entries()].sort(([a],[b])=>a.localeCompare(b));
  const manifest={format:'gfit-release-v1',version,createdAt:new Date().toISOString(),
    files:entries.map(([name,data])=>({path:name,size:data.length,sha256:sha(data)}))};
  entries.push(['gfit-release.json',Buffer.from(JSON.stringify(manifest,null,2)+'\n')]);
  const local=[],central=[];
  let offset=0;
  for(const [name,data] of entries){
    const basename=Buffer.from(name,'utf8');
    const packed=deflateRawSync(data,{level:6});
    const value=crc32(data);
    const l=Buffer.alloc(30);
    l.writeUInt32LE(0x04034b50,0);l.writeUInt16LE(20,4);l.writeUInt16LE(0x800,6);
    l.writeUInt16LE(8,8);l.writeUInt32LE(value,14);
    l.writeUInt32LE(packed.length,18);l.writeUInt32LE(data.length,22);
    l.writeUInt16LE(basename.length,26);
    local.push(l,basename,packed);
    const c=Buffer.alloc(46);
    c.writeUInt32LE(0x02014b50,0);c.writeUInt16LE(0x0314,4);
    c.writeUInt16LE(20,6);c.writeUInt16LE(0x800,8);c.writeUInt16LE(8,10);
    c.writeUInt32LE(value,16);c.writeUInt32LE(packed.length,20);
    c.writeUInt32LE(data.length,24);c.writeUInt16LE(basename.length,28);
    c.writeUInt32LE((0o100644<<16)>>>0,38);c.writeUInt32LE(offset,42);
    central.push(c,basename);
    offset+=l.length+basename.length+packed.length;
  }
  const centralBytes=central.reduce((sum,b)=>sum+b.length,0);
  const end=Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50,0);
  end.writeUInt16LE(entries.length,8);end.writeUInt16LE(entries.length,10);
  end.writeUInt32LE(centralBytes,12);end.writeUInt32LE(offset,16);
  const output=Buffer.concat([...local,...central,end]);
  if(output.length>ZIP_MAX_BYTES)throw new Error('Release ZIP excede 32 MiB.');
  return {buffer:output,manifest,sha256:sha(output)};
}
